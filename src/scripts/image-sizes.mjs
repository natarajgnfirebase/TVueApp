import prompts from 'prompts'
import kleur from 'kleur'
import { promisify } from 'util'
import fs from 'fs'
import path from 'path'
import sizeOfSync from 'image-size'
import images from '../data/images.json' with { type: 'json' }

const sizeOf = promisify(sizeOfSync)
const imagePattern = /\.(jpe?g|png|gif|webp)$/

const base = '../../assets/images/admin-sys/'

const types = {
  // the application expects the full path for header only.. why??
  header: {
    dir: 'header-banners',
    prefix: 'assets/images/admin-sys/header-banners/'
  },
  content: {
    dir: 'content-widgets',
    prefix: ''
  },
  sidebar: {
    dir: 'sidebar-widgets',
    prefix: ''
  }
}
const typeKeys = Object.keys(types)

const getImagesInDirectory = async (type) => {
  const dir = `${base}/${types[type].dir}`
  try {
    const files = await fs.promises.readdir(dir)
    return files.filter(file => file.match(imagePattern))
  } catch (err) {
    console.warn(err)
    return []
  }
}

const getImagesInJson = (type) => {
  return images[type]
    .map(image => image.file)
    .map(file => file.split('/').pop())
}

const getMissingImages = async (type) => {
  const inJson = getImagesInJson(type)
  const inDir = await getImagesInDirectory(type)
  return inJson.filter(image => !inDir.includes(image))
}

const getUntrackedImages = async (type) => {
  const inJson = getImagesInJson(type)
  const inDir = await getImagesInDirectory(type)
  return inDir.filter(image => !inJson.includes(image))
}

const doAudit = async () => {
  return typeKeys.reduce(async (acc, type) => {
    const prev = await acc
    const current = getImagesInJson(type)
    const missing = await getMissingImages(type)
    const untracked = await getUntrackedImages(type)
    return {
      ...prev,
      [type]: {
        current,
        missing,
        untracked
      }
    }
  }, Promise.resolve({}))
}

const audit = await doAudit()

const queue = await typeKeys.reduce(async (acc, type) => {
  const prev = await acc
  const typeLabel = kleur.green().bold(type)

  const typeAudit = audit[type]
  const { current, missing, untracked } = typeAudit
  let list = current
  if (!missing.length && !untracked.length) {
    console.log(`No change to ${typeLabel} image inventory; skipping…`)
  } else {
    if (missing.length) {
      console.log(`There are ${missing.length} ${typeLabel} images missing in the filesystem:`)
      console.log(kleur.grey(missing.map(file => `  • ${file}`).join('\n')))
      const { resolution } = await prompts({
        type: 'select',
        name: 'resolution',
        message: 'What would you like to do?',
        choices: [
          { title: 'Remove references', value: 'remove' },
          { title: 'Abort', description: 'The script will exit to let you mull things over', value: 'abort' }
        ]
      })
      if (resolution === 'abort') {
        console.log('Ok, come back soon! 👋')
        process.exit(0)
      }
      list = list.filter(image => !missing.includes(current))
    }

    if (untracked.length) {
      console.log(`There are ${untracked.length} new, untracked ${typeLabel} images in the filesystem:`)
      console.log(kleur.grey(untracked.map(file => `  • ${file}`).join('\n')))
      const { resolution } = await prompts({
        type: 'select',
        name: 'resolution',
        message: 'What would you like to do?',
        choices: [
          { title: 'Ignore them', description: 'You will see this message again until the images are removed or added', value: 'ignore' },
          { title: 'Add them', value: 'add' },
          { title: 'Delete them', value: 'delete' }
        ]
      })
      if (resolution === 'delete') {
        // delete these files before moving on
        await Promise.all(untracked.map(async (file) => {
          const { dir } = types[type]
          const path = `${base}/${dir}`
          return fs.promises.unlink(`${path}/${file}`)
        }))
      }
      if (resolution === 'add') {
        list = list.concat(untracked)
      }
    }
  }

  return {
    ...prev,
    [type]: list
  }
}, Promise.resolve({}))

const measureImage = async (type, file) => {
  const { dir, prefix } = types[type]
  const path = `${base}/${dir}`
  const { width, height } = await sizeOf(`${path}/${file}`)
  return {
    type,
    file: `${prefix}${file}`,
    width,
    height
  }
}

const measureImages = async (type, list) => {
  const promises = list.map(file => measureImage(type, file))
  return await Promise.all(promises)
}

const processed = typeKeys.map(async (type) => {
  return await measureImages(type, queue[type])
})

const results = (await Promise.all(processed)).flat()

const warning = `⛔️ DO NOT EDIT THIS FILE! It is generated by the ${path.basename(import.meta.url)} script.`
const res = results.reduce((acc, image) => {
  const { type, ...rest } = image
  return {
    ...acc,
    [type]: (acc[type] || []).concat(rest)
  }
}, { warning })
const json = JSON.stringify(res, null, 2)
fs.writeFileSync('../data/images.json', json)
